create table if not exists public.rescue_requests (
  id bigint generated by default as identity primary key,
  request_id text,
  request_type text,
  detail text,
  consideration text,
  created_at timestamptz not null default now(),
  user_name text,
  requester_name text,
  rescue_details text,
  health_condition text,
  considerations text,
  location text,
  location_text text,
  distance text,
  distance_text text,
  status text not null default '未対応'
);

create index if not exists idx_rescue_requests_created_at_desc
  on public.rescue_requests (created_at desc);

alter table public.rescue_requests replica identity full;

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'rescue_requests'
  ) then
    alter publication supabase_realtime add table public.rescue_requests;
  end if;
end $$;

alter table public.rescue_requests enable row level security;

drop policy if exists "exhibition_select_rescue_requests" on public.rescue_requests;
create policy "exhibition_select_rescue_requests"
  on public.rescue_requests
  for select
  to anon, authenticated
  using (true);

drop policy if exists "exhibition_insert_rescue_requests" on public.rescue_requests;
create policy "exhibition_insert_rescue_requests"
  on public.rescue_requests
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "exhibition_update_rescue_requests" on public.rescue_requests;
create policy "exhibition_update_rescue_requests"
  on public.rescue_requests
  for update
  to anon, authenticated
  using (true)
  with check (status in ('未対応', '対応中', '対応済み'));

grant usage on schema public to anon, authenticated;
grant select, insert, update on public.rescue_requests to anon, authenticated;
grant usage, select on sequence public.rescue_requests_id_seq to anon, authenticated;

